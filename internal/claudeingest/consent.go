// UserStateDir returns the per-user state directory for Claude ingestion.
// The path follows the daemon's existing UserConfigDir convention rather
// than os.UserConfigDir() to stay consistent with where the rest of the
// daemon's user-scoped state lives (~/.config/galois-edge on Unix,
// %APPDATA%\galois-edge on Windows).
func UserStateDir() (string, error) {
	return filepath.Join(config.UserConfigDir(), "claude-ingest"), nil
}

// ConsentPath returns the local consent JSON path.
func ConsentPath() (string, error) {
	dir, err := UserStateDir()
	if err != nil {
		return "", err
	}
	return filepath.Join(dir, "consent.json"), nil
}

